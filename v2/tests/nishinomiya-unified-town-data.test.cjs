#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const src=fs.readFileSync(path.join(root,'data/town-maps/28204.json'),'utf8');
const data=JSON.parse(src),raw=JSON.parse(fs.readFileSync(path.join(root,'data/nishinomiya-town-v2-premerged.topojson'),'utf8'));
assert.equal(data.schemaVersion,1);assert.equal(data.municipalityCode,'28204');assert.equal(data.boundaryYear,2020);
assert.equal(data.topo.objects.town.geometries.length,321);
assert.equal(data.kana.entries.length,321);
assert.equal(data.kana.matchedCount,321);
const names=data.topo.objects.town.geometries.map(x=>x.properties.S_NAME);
assert.equal(new Set(names).size,321);assert.ok(names.every(Boolean));
assert.equal(new Set(data.kana.entries.map(x=>x.name)).size,321);
assert.deepEqual(new Set(names),new Set(data.kana.entries.map(x=>x.name)));
assert.equal(JSON.stringify(raw),JSON.stringify(data.topo),'must not change accepted Nishinomiya B geometry');
const engine=fs.readFileSync(path.join(root,'common/js/town-map-engine.js'),'utf8');
const context={window:{}};vm.runInNewContext(engine,context);
const decoded=context.window.KussoonV2TownMap.decode(data.topo);
assert.equal(decoded.features.length,321);assert.equal(decoded.deltaEncoded,false);
assert.ok(decoded.features.every(f=>!f.d.includes('NaN')&&!f.d.includes('Infinity')));
const html=fs.readFileSync(path.join(root,'town-map/index.html'),'utf8');
assert.match(html,/KussoonV2TownMap.create/);assert.match(html,/code=q.get\('code'\)/);
console.log('nishinomiya-unified-town-data: PASS (static; browser acceptance separate)');