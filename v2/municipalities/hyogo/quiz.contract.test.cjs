'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
const app=fs.readFileSync(path.join(root,'v2/municipalities/shared/quiz-app.js'),'utf8');
const areas=idx.entries.filter(e=>e.pref==='28'),codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'28');assert.equal(cfg.name,'兵庫県');
assert.equal(cfg.expectedAreaCount,49);
assert.equal(idx.count,1905);
assert.equal(manifest.entries.find(e=>e.pref==='28').regions,49);
assert.equal(areas.length,49);
assert.deepEqual(cfg.regions.map(r=>r.name),['神戸','阪神南','阪神北','東播磨','北播磨','中播磨','西播磨','但馬','丹波','淡路']);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[9,3,5,5,6,4,7,5,2,3]);
assert.deepEqual(cfg.regions.map(r=>r.reading),['こうべ','はんしんみなみ','はんしんきた','ひがしはりま','きたはりま','なかはりま','にしはりま','たじま','たんば','あわじ']);
assert.equal(codes.length,49);assert.equal(new Set(codes).size,49);
assert.deepEqual([...codes].sort(),areas.map(e=>e.code).sort(),'All 49 quiz codes match national 2026 index exactly');
assert(areas.every(e=>/^[ぁ-ゖー]+$/.test(e.reading)),'All 49 area readings are available');
const wards=areas.filter(e=>e.fullName.startsWith('神戸市')&&e.name.endsWith('区'));
assert.equal(wards.length,9,'Nine Kobe wards are distinct quiz areas');
assert.deepEqual(cfg.regions.find(r=>r.key==='kobe').codes.slice().sort(),wards.map(e=>e.code).sort(),'Kobe region contains all nine wards');
const towns=areas.filter(e=>!e.name.endsWith('市')&&!e.name.endsWith('区'));
assert.equal(towns.length,12);assert.equal(Object.keys(cfg.countyByTown).length,12);
for(const town of towns){
 const county=cfg.countyByTown[town.name];
 assert(county&&county[0].endsWith('郡')&&/^[ぁ-ゖー]+$/.test(county[1]),'Missing county and reading: '+town.name);
}
assert.equal(cfg.regionSource,'https://web.pref.hyogo.lg.jp/area/');
assert(page.includes('new Set(codes).size!==49'),'Overview checks the correct prefecture area count');
assert(page.includes("cfg.countyByTown[item.name]"),'Overview shows county prefixes');
assert(page.includes("key:'all',name:'全域'"),'Overview displays full prefecture option');
assert(page.includes("ruby.append(make('rt',region.reading))"),'Overview regional reading');
assert(page.includes('quiz.html?mode=1')&&page.includes('quiz.html?mode=2'),'Both quizzes linked');
assert(quiz.includes('data-region-config="./regions.json"'),'Standard shared region configuration');
assert(quiz.includes('regional-quiz.js')&&quiz.includes('quiz-app.js?v=20261110-all-areas'),'Current shared quiz runtime');
assert(quiz.includes('id="prefReset"')&&quiz.includes('id="retryMissed"'),'Map reset and retry controls preserved');
assert(quiz.includes('/common/site-footer.js'),'Shared footer');
assert(app.includes("key:'all',name:'全域'"),'Shared quiz offers whole prefecture');
assert(app.includes("fitMap(current,selectedRange==='all')"),'Whole-prefecture map fit');
assert(app.includes('const COUNTY_BY_TOWN=config.countyByTown||{}'),'Counties from config');
console.log('Hyogo V2: 10 preserved regions, 49 codes, 9 Kobe wards, 12 towns, full-prefecture and both quiz modes PASS');
