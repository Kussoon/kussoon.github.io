'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const areas=idx.entries.filter(e=>e.pref==='19'&&!((cfg.excludedAreaCodes||[]).includes(e.code)));
const codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'19');assert.equal(cfg.expectedAreaCount,27);
assert.equal(manifest.entries.find(e=>e.pref==='19').regions,27);
assert.equal(areas.length,27);assert.equal(cfg.regions.length,4);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[7,3,5,12]);
assert(cfg.regions.every(r=>r.codes.length>=2),'No one-area quiz region');
assert.deepEqual([...codes].sort(),areas.map(e=>e.code).sort());assert.equal(new Set(codes).size,27);
assert(cfg.regions.every(r=>r.name&&/^[ぁ-ゖー]+$/.test(r.reading)));
const towns=areas.filter(e=>/町$|村$/.test(e.name)).map(e=>e.name).sort();
assert.deepEqual(Object.keys(cfg.countyByTown).sort(),towns);
for(const town of towns)assert(/^[ぁ-ゖー]+$/.test(cfg.countyByTown[town][1]),town);
assert(cfg.regionSource.startsWith('https://www.'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8'),quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
assert(page.includes("key:'all',name:'全域'"));assert(page.includes('全27区域'));
assert(quiz.includes('regional-quiz.js'));assert(quiz.includes('quiz-app.js'));
console.log('山梨県 27 areas, 4 regions, whole-prefecture mode: PASS');
