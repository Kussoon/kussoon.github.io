'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
const app=fs.readFileSync(path.join(root,'v2/municipalities/shared/quiz-app.js'),'utf8');
const geometry=idx.entries.filter(e=>e.pref==='30');
const municipalities=geometry.filter(e=>e.code!=='30000');
const codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'30');assert.equal(cfg.name,'和歌山県');
assert.equal(manifest.entries.find(e=>e.pref==='30').regions,31);
assert.equal(geometry.length,31);assert.equal(municipalities.length,30);
assert.deepEqual(cfg.excludedAreaCodes,['30000']);
assert.equal(geometry.find(e=>e.code==='30000').name,'所属未定地');
assert.equal(cfg.expectedAreaCount,30);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[3,2,4,4,7,4,6]);
assert.deepEqual(cfg.regions.map(r=>r.name),['海草','那賀','伊都','有田','日高','西牟婁','東牟婁']);
assert.equal(codes.length,30);assert.equal(new Set(codes).size,30);
assert.deepEqual([...codes].sort(),municipalities.map(e=>e.code).sort(),'All 30 municipalities covered exactly once');
for(const item of municipalities)assert.ok(/^[ぁ-ゖー]+$/.test(item.reading),'Missing municipality reading: '+item.name);
for(const region of cfg.regions)assert.ok(/^[ぁ-ゖー]+$/.test(region.reading),'Missing region reading: '+region.name);
const towns=municipalities.filter(e=>!e.name.endsWith('市'));
assert.equal(towns.length,21);assert.equal(Object.keys(cfg.countyByTown).length,21);
for(const town of towns){
 const county=cfg.countyByTown[town.name];
 assert.ok(county&&county[0].endsWith('郡')&&/^[ぁ-ゖー]+$/.test(county[1]),'Missing county name/reading: '+town.name);
}
assert.equal(cfg.regionSource,'https://www.pref.wakayama.lg.jp/prefg/010100/reiki/reiki_honbun/k501RG00000090.html');
assert.equal(cfg.countySource,'https://www.j-lis.go.jp/spd/code-address/kinki/cms_15114183.html');
assert(page.includes("cfg.countyByTown[item.name]"),'County in municipality list');
assert(page.includes("cfg.excludedAreaCodes.includes(e.code)"),'Unassigned placeholder hidden from study list');
assert(page.includes('id="regions"')&&page.includes('id="items"'));
assert(page.includes('quiz.html?mode=1')&&page.includes('quiz.html?mode=2'));
assert(page.includes('idx.count!==1905'),'Full nationwide index preserved');
assert(quiz.includes('data-region-config="./regions.json"'));
assert(quiz.includes('regional-quiz.js')&&quiz.includes('quiz-app.js'));
assert(quiz.includes('id="prefReset"')&&quiz.includes('id="retryMissed"'));
assert(quiz.includes('/common/site-footer.js'));
assert(app.includes('const excluded=new Set(config.excludedAreaCodes||[]);'),'Excluded codes are configuration-driven and opt-in');
assert(app.includes('const shapes=rawShapes.filter(g=>!excluded.has(String(g.properties.N03_007)))'),'Excluded shapes never enter quiz');
assert(app.includes('proximity=Core.proximity(all,shapes);'),'4-choice proximity uses same filtered shapes');
assert(app.includes('const COUNTY_BY_TOWN=config.countyByTown||{}'));
assert(app.includes("mode=query.get('mode')==='1'?1:2"));
console.log('Wakayama 30/30 municipalities, seven official regions, 21 counties, modes 1/2: PASS');
