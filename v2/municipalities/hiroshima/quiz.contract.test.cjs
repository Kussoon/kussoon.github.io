'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
const app=fs.readFileSync(path.join(root,'v2/municipalities/shared/quiz-app.js'),'utf8');
const core=fs.readFileSync(path.join(root,'v2/municipalities/shared/regional-quiz.js'),'utf8');
const areas=idx.entries.filter(e=>e.pref==='34'),codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'34');assert.equal(cfg.name,'広島県');
assert.equal(cfg.expectedAreaCount,30);
assert.equal(idx.count,1905);
assert.equal(manifest.entries.find(e=>e.pref==='34').regions,30);
assert.equal(areas.length,30);
assert.deepEqual(cfg.regions.map(r=>r.name),['広島','広島西','呉','芸北','広島中央','尾三','福山・府中','備北']);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[12,2,2,3,3,3,3,2]);
assert.deepEqual(cfg.regions.map(r=>r.reading),['ひろしま','ひろしまにし','くれ','げいほく','ひろしまちゅうおう','びさん','ふくやま・ふちゅう','びほく']);
assert.equal(codes.length,30);assert.equal(new Set(codes).size,30);
assert.deepEqual([...codes].sort(),areas.map(e=>e.code).sort(),'All 30 administrative quiz areas covered once');
assert(areas.every(e=>/^[ぁ-ゖー]+$/.test(e.reading)),'All area readings are available');
const wards=areas.filter(e=>e.fullName.startsWith('岡山市')&&e.name.endsWith('区'));
assert.equal(wards.length,8,'Eight Hiroshima wards are distinct quiz areas');
assert.deepEqual(cfg.regions.find(r=>r.key==='hiroshima').codes.filter(c=>wards.some(e=>e.code===c)).sort(),wards.map(e=>e.code).sort(),'Eight Hiroshima wards belong to Bizen');
assert(wards.every(e=>e.fullName.startsWith('岡山市')),'Ward names contain their parent city');
const towns=areas.filter(e=>!e.name.endsWith('市')&&!e.name.endsWith('区'));
assert.equal(towns.length,9);assert.equal(Object.keys(cfg.countyByTown).length,9);
assert.equal(new Set(Object.values(cfg.countyByTown).map(row=>row[0])).size,5);
for(const t of towns){
 const county=cfg.countyByTown[t.name];
 assert(county&&county[0].endsWith('郡')&&/^[ぁ-ゖー]+$/.test(county[1]),'Missing county and reading: '+t.name);
}
assert.equal(cfg.regionSource,'https://www.pref.hiroshima.jp/uploaded/life/771490_7152944_misc.pdf');
assert.equal(cfg.countySource,'https://www.j-lis.go.jp/spd/code-address/chuugoku/cms_15514184.html');
assert(page.includes("cfg.countyByTown[item.name]"),'List includes county text');
assert(page.includes("ruby.append(make('rt',region.reading))"),'Regional selector ruby');
assert(page.includes('quiz.html?mode=1')&&page.includes('quiz.html?mode=2'),'Both quizzes linked');
assert(page.includes('idx.count!==1905')&&page.includes('cfg.regions.length!==8'),'2026 and region count runtime checks');
assert(quiz.includes('data-region-config="./regions.json"'),'Standard region data');
assert(quiz.includes('regional-quiz.js')&&quiz.includes('quiz-app.js'),'Shared quiz runtime');
assert(quiz.includes('id="prefReset"')&&quiz.includes('id="retryMissed"'),'Two fit levels and missed question retry');
assert(quiz.includes('/common/site-footer.js'),'Shared site footer');
assert(app.includes('minZoom:0.25')&&app.includes('const COUNTY_BY_TOWN=config.countyByTown||{}'),'Zoom and county common contracts unchanged');
assert(core.includes('proximity')&&core.includes('wrongCodes'),'Common four-choice and scoring contracts preserved');
console.log('Hiroshima V2: 8 regions 12+2+2+3+3+3+3+2 areas, eight wards, 9 towns, both quiz modes PASS');
