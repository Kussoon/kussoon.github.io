'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const config=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const index=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const kyoto=index.entries.filter(e=>e.pref==='26'),actual=kyoto.map(x=>x.code).sort(),all=config.regions.flatMap(r=>r.codes);
assert.equal(config.prefecture,'26');assert.equal(config.expectedAreaCount,36);
assert.equal(manifest.entries.find(x=>x.pref==='26').regions,36);
assert.equal(index.count,1905);assert.equal(kyoto.length,36);
assert.equal(config.regions.length,8);assert.equal(all.length,36);assert.equal(new Set(all).size,36);
assert.deepEqual([...all].sort(),actual,'No lost/duplicate Kyoto codes');
assert.equal(config.regions.find(x=>x.key==='kyoto-city').codes.length,11);
assert.equal(config.regions.find(x=>x.key==='tango').codes.length,4,'Tango four municipalities');
assert.equal(config.regions.find(x=>x.key==='soraku-east').codes.length,3,'Soraku East three municipalities');
assert.equal(Object.keys(config.countyByTown).length,11,'All Kyoto towns and village have counties');
assert.equal(kyoto.filter(x=>x.reading).length,36,'Reading data complete');
assert(html.includes('name="robots" content="noindex,follow"'));
assert(html.includes('fetch(\'./regions.json\')'));
assert(html.includes('<script defer src="/common/site-footer.js">'));
console.log('Kyoto V2 region baseline: PASS (36/36 areas, 8 regions)');
