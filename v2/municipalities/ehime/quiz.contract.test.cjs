'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
const app=fs.readFileSync(path.join(root,'v2/municipalities/shared/quiz-app.js'),'utf8');
const areas=idx.entries.filter(e=>e.pref==='38'),codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'38');assert.equal(cfg.name,'愛媛県');assert.equal(cfg.expectedAreaCount,20);
assert.equal(manifest.entries.find(e=>e.pref==='38').regions,20);
assert.equal(idx.count,1905);assert.equal(areas.length,20);
assert.deepEqual(cfg.regions.map(r=>r.name),['東予','中予','南予']);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[5,6,9]);
assert.deepEqual(cfg.regions.map(r=>r.reading),['とうよ','ちゅうよ','なんよ']);
assert.equal(codes.length,20);assert.equal(new Set(codes).size,20);
assert.deepEqual([...codes].sort(),areas.map(e=>e.code).sort(),'All 20 codes covered exactly once');
const towns=areas.filter(e=>!e.name.endsWith('市'));
assert.equal(towns.length,9);assert.equal(Object.keys(cfg.countyByTown).length,9);
assert.equal(new Set(Object.values(cfg.countyByTown).map(x=>x[0])).size,7);
for(const t of towns){const county=cfg.countyByTown[t.name];assert(county&&county[0].endsWith('郡')&&/^[ぁ-ゖー]+$/.test(county[1]),t.name);}
assert(areas.every(e=>/^[ぁ-ゖー]+$/.test(e.reading)),'Readings available');
assert.equal(cfg.regionSource,'https://www.pref.ehime.jp/page/14990.html');
assert.equal(cfg.countySource,'https://www.j-lis.go.jp/spd/code-address/shikoku/cms_15914186.html');
assert(page.includes('new Set(codes).size!==20')&&page.includes('cfg.regions.length!==3'),'Runtime counts correct');
assert(page.includes("key:'all',name:'全域'")&&page.includes("cfg.countyByTown[item.name]"),'Whole-prefecture and county labels');
assert(page.includes('quiz.html?mode=1')&&page.includes('quiz.html?mode=2'),'Both modes');
assert(quiz.includes('data-region-config="./regions.json"')&&quiz.includes('quiz-app.js?v=20261110-all-areas'));
assert(quiz.includes('id="prefReset"')&&quiz.includes('id="retryMissed"'));
assert(app.includes("key:'all',name:'全域'")&&app.includes('const COUNTY_BY_TOWN=config.countyByTown||{}'));
console.log('Ehime V2 PASS: Toyo 5, Chuyo 6, Nanyo 9, 20 areas, 9 towns 7 counties, both quiz modes and all-area');
