'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
const app=fs.readFileSync(path.join(root,'v2/municipalities/shared/quiz-app.js'),'utf8');
const areas=idx.entries.filter(e=>e.pref==='36'),codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'36');assert.equal(cfg.name,'徳島県');
assert.equal(cfg.expectedAreaCount,24);
assert.equal(idx.count,1905);
assert.equal(manifest.entries.find(e=>e.pref==='36').regions,24);
assert.equal(areas.length,24);
assert.deepEqual(cfg.regions.map(r=>r.name),['東部','南部','西部']);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[15,5,4]);
assert.deepEqual(cfg.regions.map(r=>r.reading),['とうぶ','なんぶ','せいぶ']);
assert.equal(codes.length,24);assert.equal(new Set(codes).size,24);
assert.deepEqual([...codes].sort(),areas.map(e=>e.code).sort(),'All 24 quiz codes covered once');
assert(areas.every(e=>/^[ぁ-ゖー]+$/.test(e.reading)),'All readings provided');
const towns=areas.filter(e=>!e.name.endsWith('市'));
assert.equal(towns.length,16);assert.equal(Object.keys(cfg.countyByTown).length,16);
assert.equal(new Set(Object.values(cfg.countyByTown).map(row=>row[0])).size,8);
for(const town of towns){const county=cfg.countyByTown[town.name];assert(county&&county[0].endsWith('郡')&&/^[ぁ-ゖー]+$/.test(county[1]),'County missing: '+town.name);}
assert(page.includes('new Set(codes).size!==24'),'Count check is 24 not inherited');
assert(page.includes('cfg.regions.length!==3'),'Three region count checked');
assert(page.includes("key:'all',name:'全域'"),'Overview has all-area option');
assert(page.includes('quiz.html?mode=1')&&page.includes('quiz.html?mode=2'),'Both quiz modes linked');
assert(quiz.includes('data-region-config="./regions.json"'));
assert(quiz.includes('quiz-app.js?v=20261110-all-areas'),'Versioned runtime');
assert(quiz.includes('id="prefReset"')&&quiz.includes('id="retryMissed"'));
assert(app.includes("key:'all',name:'全域'"));
assert(app.includes('const COUNTY_BY_TOWN=config.countyByTown||{}'));
console.log('Tokushima V2 PASS: East15 South5 West4, 24 areas, 16 town/village county labels, all-area mode');
