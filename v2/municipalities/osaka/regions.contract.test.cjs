'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const config=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const index=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const osaka=index.entries.filter(e=>e.pref==='27'),actual=osaka.map(x=>x.code).sort(),all=config.regions.flatMap(r=>r.codes);
assert.equal(config.prefecture,'27');assert.equal(config.expectedAreaCount,72);
assert.equal(manifest.entries.find(x=>x.pref==='27').regions,72);
assert.equal(index.count,1905);assert.equal(osaka.length,72);
assert.equal(config.regions.length,8);assert.equal(all.length,72);assert.equal(new Set(all).size,72);
assert.deepEqual([...all].sort(),actual,'No lost/duplicate Osaka codes');
assert.equal(config.regions.find(x=>x.key==='osaka').codes.length,24);
assert.equal(config.regions.find(x=>x.key==='senboku').codes.filter(x=>x.startsWith('2714')).length,7,'Seven Sakai wards');
assert.equal(osaka.filter(x=>x.reading).length,72,'Reading data complete');
assert(html.includes('name="robots" content="noindex,follow"'));
assert(html.includes('fetch(\'./regions.json\')'));
assert(html.includes('<script defer src="/common/site-footer.js">'));
console.log('Osaka V2 region baseline: PASS (72/72 areas, 8 regions)');
