assert(areas.every(e=>/^[ぁ-ゖー]+$/.test(e.reading)),'All readings provided');
assert.equal(cfg.regionSource,'https://www.pref.kochi.lg.jp/doc/2019120600074/file_contents/file_2022421416538_1.pdf');
