assert(page.includes('new Set(codes).size!==34')&&page.includes('cfg.regions.length!==6'),'Runtime count guard matches Kochi');
assert(page.includes("key:'all',name:'全域'")&&page.includes('cfg.countyByTown[item.name]'),'Overview full-area and county labels');
