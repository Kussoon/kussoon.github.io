'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'../../..');
const cfg=JSON.parse(fs.readFileSync(path.join(__dirname,'regions.json'),'utf8'));
const idx=JSON.parse(fs.readFileSync(path.join(root,'v2/progressive-preview/label-index.json'),'utf8'));
const manifest=JSON.parse(fs.readFileSync(path.join(root,'v2/data/national/2026-common/national-2026-pilot/manifest.json'),'utf8'));
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const quiz=fs.readFileSync(path.join(__dirname,'quiz.html'),'utf8');
const app=fs.readFileSync(path.join(root,'v2/municipalities/shared/quiz-app.js'),'utf8');
const core=fs.readFileSync(path.join(root,'v2/municipalities/shared/regional-quiz.js'),'utf8');
const municipalities=idx.entries.filter(e=>e.pref==='31');
const codes=cfg.regions.flatMap(r=>r.codes);
assert.equal(cfg.prefecture,'31');assert.equal(cfg.name,'鳥取県');
assert.equal(cfg.expectedAreaCount,19);
assert.equal(idx.count,1905);
assert.equal(manifest.entries.find(e=>e.pref==='31').regions,19);
assert.equal(municipalities.length,19);
assert.deepEqual(cfg.regions.map(r=>r.name),['東部','中部','西部']);
assert.deepEqual(cfg.regions.map(r=>r.codes.length),[5,5,9]);
assert.deepEqual(cfg.regions.map(r=>r.reading),['とうぶ','ちゅうぶ','せいぶ']);
assert.equal(codes.length,19);assert.equal(new Set(codes).size,19);
assert.deepEqual([...codes].sort(),municipalities.map(e=>e.code).sort(),'All 19 municipalities covered once');
assert(municipalities.every(e=>/^[ぁ-ゖー]+$/.test(e.reading)),'All municipality readings present');
const towns=municipalities.filter(e=>!e.name.endsWith('市'));
assert.equal(towns.length,15);assert.equal(Object.keys(cfg.countyByTown).length,15);
const countyNames=[...new Set(Object.values(cfg.countyByTown).map(v=>v[0]))].sort();
assert.deepEqual(countyNames,['八頭郡','岩美郡','日野郡','東伯郡','西伯郡'].sort());
for(const town of towns){
 const county=cfg.countyByTown[town.name];
 assert(county&&county[0].endsWith('郡')&&/^[ぁ-ゖー]+$/.test(county[1]),town.name+' requires county and reading');
}
assert.equal(cfg.regionSource,'https://www.pref.tottori.lg.jp/34749.htm');
assert.equal(cfg.countySource,'https://www.pref.tottori.lg.jp/153648.htm');
assert(page.includes("cfg.countyByTown[item.name]"),'List includes counties');
assert(page.includes("ruby.append(make('rt',region.reading))"),'Regional selector includes ruby');
assert(page.includes('quiz.html?mode=1')&&page.includes('quiz.html?mode=2'),'Both quiz modes linked');
assert(page.includes('id="regions"')&&page.includes('id="items"'),'Selector and list available');
assert(page.includes('idx.count!==1905'),'Nationwide index invariant kept');
assert(!page.includes('excludedAreaCodes'),'Tottori does not need an exclusion exception');
assert(quiz.includes('data-region-config="./regions.json"'),'Uses standard regional config');
assert(quiz.includes('regional-quiz.js')&&quiz.includes('quiz-app.js'),'Uses existing common quiz runtime');
assert(quiz.includes('id="prefReset"')&&quiz.includes('id="retryMissed"'),'Fit and missed questions buttons');
assert(quiz.includes('/common/site-footer.js'),'Common site footer');
assert(app.includes('minZoom:0.25'),'Existing zoom-out allowance unchanged');
assert(app.includes('const COUNTY_BY_TOWN=config.countyByTown||{}'),'Existing county formatting unchanged');
assert(app.includes("mode=query.get('mode')==='1'?1:2"),'Existing quiz mode selection unchanged');
assert(core.includes('proximity')&&core.includes('wrongCodes'),'Existing scoring and proximity kept');
console.log('Tottori V2: 19 municipalities, 3 regions, 15 county mappings and both quiz modes: PASS');
