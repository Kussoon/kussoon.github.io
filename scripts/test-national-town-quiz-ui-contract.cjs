'use strict';
const assert=require('node:assert/strict');
const ui=require('../v2/common/js/town-svg-quiz-ui.js');
const el=()=>({hidden:false,textContent:'',classList:{items:new Set(),add(x){this.items.add(x)},remove(x){this.items.delete(x)}},replaceChildren(){this.cleared=true}});
const status=el(),panel=el(),results=el(),body=el();
status.textContent='中断した問題：「前回の町」';
ui.start({mode:2,status,panel,results,body});
assert.equal(status.textContent,'クイズ2を実施中です。');
assert.equal(panel.hidden,false);assert.equal(results.hidden,true);assert(body.classList.items.has('town-quiz-mode'));
const question=el(),feedback=el(),reveal=el(),next=el(),choices=el();
const wrongPlaces=new Set(['以前の誤答']);let blinkStopped=0;
ui.clearQuestion({stopBlink:()=>blinkStopped++,wrongPlaces,choices,next,reveal,feedback});
assert.equal(blinkStopped,1);assert.equal(wrongPlaces.size,0);assert(choices.cleared);assert(next.hidden);assert(reveal.hidden);assert.equal(feedback.textContent,'');
ui.showQuestion({mode:1,target:'試験町',label:x=>x+'（しけんちょう）',question,feedback,reveal});
assert.equal(question.textContent,'「試験町（しけんちょう）」の場所を押してください。');assert.equal(feedback.textContent,'地図の区域を押してください。');assert.equal(reveal.hidden,false);
ui.showQuestion({mode:2,target:'試験町',label:x=>x,question,feedback,reveal});
assert.equal(question.textContent,'黄色く点滅する町名を選んでください。');
ui.correct({feedback,reveal,next,index:0,total:2,message:'正解です！ 試験町'});
assert.equal(feedback.textContent,'正解です！ 試験町');assert.equal(next.textContent,'次の問題へ');assert.equal(next.hidden,false);assert.equal(reveal.hidden,true);
ui.correct({feedback,reveal,next,index:1,total:2,message:'正解です！ 最終町'});
assert.equal(next.textContent,'結果発表');
const result=el();ui.finish({body,panel,results,result,quit:true,answered:1,total:3,score:2,wrongCount:1});
assert.equal(result.textContent,'途中終了：1 / 3問終了（間違えた問題 1件）');assert(!body.classList.items.has('town-quiz-mode'));assert(panel.hidden);assert(!results.hidden);
ui.finish({body,panel,results,result,quit:false,answered:3,total:3,score:2,wrongCount:1});
assert.equal(result.textContent,'3問中 2点（間違えた問題 1件）');
assert.throws(()=>ui.start({mode:3,status,panel,results,body}),TypeError);
assert.throws(()=>ui.correct({feedback,reveal,next,index:3,total:2,message:''}),TypeError);
console.log('PASS NATIONAL_TOWN_QUIZ_UI_CONTRACT');
